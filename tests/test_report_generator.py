import fitz
from src.report_generator import generate_gem_verification_pdf


def test_generate_gem_verification_pdf_compliant():
    audit_data = [
        {"Stage": "Phase 7 Statutory", "Rule Checked": "GSTIN Verification", "Status": "PASS", "Finding Details": "Checksum valid."},
        {"Stage": "Phase 9 Forensic", "Rule Checked": "PAN in GSTIN Check", "Status": "PASS", "Finding Details": "Embedded PAN matches standalone."},
        {"Stage": "Phase 9 Forensic", "Rule Checked": "Turnover Reconciliation", "Status": "PASS", "Finding Details": "Variance within tolerance."}
    ]

    pdf_bytes = generate_gem_verification_pdf(
        tender_id="TND-2026-001 (Oil & Gas Infrastructure)",
        bidder_id="BID-A1B2C",
        company_name="TechVanguard Solutions Pvt Ltd",
        gstin_no="07AAACT1234K1ZI",
        pan_no="AAACT1234K",
        pan_entity_type="Company",
        turnover_gst="Rs. 1245 Lakhs",
        turnover_bs="Rs. 1250 Lakhs",
        compliance_status="COMPLIANT",
        risk_rating="LOW",
        risk_badge="100.0% (ML Model)",
        inconsistencies_count=0,
        audit_data=audit_data,
        officer_remarks="Approved for technical tender evaluation."
    )

    assert isinstance(pdf_bytes, bytes)
    assert len(pdf_bytes) > 2000

    # Verify that the generated bytes can be parsed by PyMuPDF as a valid 1-page PDF
    doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    assert doc.page_count == 1
    page = doc[0]
    text = page.get_text()

    assert "GOVERNMENT E-MARKETPLACE" in text
    assert "TechVanguard Solutions Pvt Ltd" in text
    assert "07AAACT1234K1ZI" in text
    assert "AAACT1234K" in text
    assert "COMPLIANT" in text
    assert "0 Found" in text
    assert "Approved for technical tender evaluation." in text
    doc.close()


def test_generate_gem_verification_pdf_disqualified_discrepancies():
    audit_data = [
        {"Stage": "Phase 9 Forensic", "Rule Checked": "PAN in GSTIN Check", "Status": "FAIL", "Finding Details": "CRITICAL MISMATCH standalone vs embedded."},
        {"Stage": "Phase 9 Forensic", "Rule Checked": "Turnover Variance", "Status": "FAIL", "Finding Details": "Variance 60% exceeds limit."}
    ]

    pdf_bytes = generate_gem_verification_pdf(
        tender_id="TND-2026-002 (Civil Works)",
        bidder_id="BID-FRAUD-01",
        company_name="FakeCorp Logistics Pvt Ltd",
        gstin_no="07AABCK8888P1ZI",
        pan_no="AABCF9999M",
        pan_entity_type="Company",
        turnover_gst="Rs. 600 Lakhs",
        turnover_bs="Rs. 1500 Lakhs",
        compliance_status="DISQUALIFIED",
        risk_rating="CRITICAL",
        risk_badge="98.2% (ML Model)",
        inconsistencies_count=2,
        audit_data=audit_data,
        officer_remarks="Disqualified due to fraudulent PAN mismatch."
    )

    assert isinstance(pdf_bytes, bytes)
    assert len(pdf_bytes) > 2000

    doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    assert doc.page_count == 1
    text = doc[0].get_text()

    assert "FakeCorp Logistics Pvt Ltd" in text
    assert "DISQUALIFIED" in text
    assert "CRITICAL" in text
    assert "2 Found" in text
    doc.close()
